def article_text(article: dict) -> str:
    head = f"{article['number']}({article['title']})" if article.get("title") else article["number"]
    parts = []
    if article.get("text"):
        parts.append(article["text"])
    for para in article.get("paragraphs", []):
        line = f"{para['number']} {para['text']}"
        for item in para.get("items", []):
            line += f"\n{item['number']} {item['text']}"
        parts.append(line)
    return ANNOTATION.sub("", head + " " + "\n".join(parts)).strip()


def load_laws() -> dict[str, dict]:
    laws = {}
    wanted = {law for _, law, _ in STATUTES}
    for path in sorted(CORPUS.glob("*.json")):
        data = json.loads(path.read_text())
        if data["law_name"] in wanted and data["law_name"] not in laws:
            laws[data["law_name"]] = {"data": data, "file": path.name}
    missing = wanted - laws.keys()
    if missing:
        raise SystemExit(f"laws not found in corpus: {missing}")
    return laws


